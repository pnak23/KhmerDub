-- KhmerDub AI - M2 job engine: attempts with fencing tokens, Spring-owned leases, new stages/statuses.
--
-- Recovery model:
--   * Every dispatch of a chunk creates a NEW processing_attempts row. Its id is the fencing token: it is the
--     Celery task id, it appears in every worker callback and in every output path.
--   * Spring owns the lease. Workers renew it with heartbeats. An expired lease marks the attempt LOST and
--     the chunk is reassigned to a new attempt.
--   * Only the chunk's current attempt may publish results. Results from any other attempt are rejected.

-- ---------------------------------------------------------------------------
-- processing_attempts
-- ---------------------------------------------------------------------------
CREATE TABLE processing_attempts (
    id                  uuid PRIMARY KEY,               -- generated by the API; = fencing token = Celery task id
    chunk_id            uuid         NOT NULL REFERENCES processing_chunks (id) ON DELETE CASCADE,
    attempt_no          integer      NOT NULL,
    status              varchar(20)  NOT NULL DEFAULT 'DISPATCHED',
    counts_toward_limit boolean      NOT NULL DEFAULT true,  -- false for infrastructure losses (claim timeout etc.)
    worker              varchar(200),
    dispatched_at       timestamptz  NOT NULL DEFAULT now(),
    claim_deadline      timestamptz  NOT NULL,
    claimed_at          timestamptz,
    last_heartbeat_at   timestamptz,
    lease_expires_at    timestamptz,
    finished_at         timestamptz,
    progress            numeric(5, 2) NOT NULL DEFAULT 0,
    end_reason          varchar(40),
    error_details       text,
    metrics             jsonb        NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_processing_attempts_chunk_no UNIQUE (chunk_id, attempt_no),
    CONSTRAINT ck_processing_attempts_no CHECK (attempt_no >= 1),
    CONSTRAINT ck_processing_attempts_status CHECK (status IN
        ('DISPATCHED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'LOST', 'CANCELLED')),
    CONSTRAINT ck_processing_attempts_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_processing_attempts_end_reason CHECK (end_reason IS NULL OR end_reason IN
        ('COMPLETED', 'WORKER_ERROR', 'INVALID_INPUT', 'LEASE_EXPIRED', 'CLAIM_TIMEOUT', 'REDELIVERED',
         'DISPATCH_FAILED', 'CANCELLED', 'JOB_FAILED'))
);
-- At most one live attempt per chunk.
CREATE UNIQUE INDEX uq_processing_attempts_one_live ON processing_attempts (chunk_id)
    WHERE status IN ('DISPATCHED', 'RUNNING');
CREATE INDEX ix_processing_attempts_live ON processing_attempts (status, lease_expires_at, claim_deadline)
    WHERE status IN ('DISPATCHED', 'RUNNING');
CREATE TRIGGER trg_processing_attempts_updated_at BEFORE UPDATE ON processing_attempts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- processing_chunks: lease/dispatch fields move to attempts; chunks gain current attempt, queue, params
-- ---------------------------------------------------------------------------
DROP INDEX ix_processing_chunks_recovery;
ALTER TABLE processing_chunks
    DROP COLUMN dispatch_token,
    DROP COLUMN lease_expires_at,
    DROP COLUMN dispatched_at,
    ADD COLUMN current_attempt_id uuid REFERENCES processing_attempts (id) ON DELETE SET NULL,
    ADD COLUMN queue varchar(20) NOT NULL DEFAULT 'cpu',
    ADD COLUMN params jsonb NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN progress numeric(5, 2) NOT NULL DEFAULT 0,
    ADD COLUMN not_before timestamptz,      -- back-off before the next dispatch
    ADD CONSTRAINT ck_processing_chunks_queue CHECK (queue IN ('cpu', 'io')),
    ADD CONSTRAINT ck_processing_chunks_progress CHECK (progress BETWEEN 0 AND 100);

-- Stages that are not about a time range (e.g. inspecting the file) have no start/end.
ALTER TABLE processing_chunks
    ALTER COLUMN start_ms DROP NOT NULL,
    ALTER COLUMN end_ms DROP NOT NULL,
    DROP CONSTRAINT ck_processing_chunks_times,
    -- Both NULL, or both set and valid. (Spelled out: a CHECK that evaluates to NULL would pass.)
    ADD CONSTRAINT ck_processing_chunks_times CHECK (
        (start_ms IS NULL AND end_ms IS NULL)
        OR (start_ms IS NOT NULL AND end_ms IS NOT NULL AND start_ms >= 0 AND end_ms > start_ms));

ALTER TABLE processing_chunks
    DROP CONSTRAINT ck_processing_chunks_stage,
    ADD CONSTRAINT ck_processing_chunks_stage CHECK (stage IN
        ('INSPECT_MEDIA', 'EXTRACT_AUDIO', 'MERGE_AUDIO', 'DETECT_LANGUAGE', 'TRANSCRIBE', 'DIARIZE',
         'RECONCILE_SPEAKERS', 'TRANSLATE', 'TTS', 'ASSEMBLE', 'MIX', 'SUBTITLE', 'EXPORT', 'VALIDATE'));

CREATE INDEX ix_processing_chunks_dispatch ON processing_chunks (status, queue, not_before);

-- ---------------------------------------------------------------------------
-- processing_jobs: transitional statuses, new job type, attempt budget, result
-- ---------------------------------------------------------------------------
DROP INDEX uq_processing_jobs_one_active;
ALTER TABLE processing_jobs
    DROP CONSTRAINT ck_processing_jobs_status,
    ADD CONSTRAINT ck_processing_jobs_status CHECK (status IN
        ('QUEUED', 'RUNNING', 'PAUSING', 'PAUSED', 'CANCELLING', 'COMPLETED', 'FAILED', 'CANCELLED')),
    DROP CONSTRAINT ck_processing_jobs_type,
    ADD CONSTRAINT ck_processing_jobs_type CHECK (job_type IN
        ('IMPORT', 'EXTRACT_AUDIO', 'TRANSCRIBE', 'TRANSLATE', 'GENERATE_AUDIO', 'REGENERATE_CLIPS', 'EXPORT',
         'FULL_PIPELINE')),
    ADD COLUMN max_attempts integer NOT NULL DEFAULT 3,
    ADD COLUMN result_asset_id uuid REFERENCES media_assets (id) ON DELETE SET NULL,
    ADD CONSTRAINT ck_processing_jobs_max_attempts CHECK (max_attempts BETWEEN 1 AND 10);
CREATE UNIQUE INDEX uq_processing_jobs_one_active ON processing_jobs (project_id, job_type)
    WHERE status IN ('QUEUED', 'RUNNING', 'PAUSING', 'PAUSED', 'CANCELLING');

-- ---------------------------------------------------------------------------
-- job_events: link to the attempt, and a strictly increasing sequence for ordering
-- ---------------------------------------------------------------------------
ALTER TABLE job_events
    ADD COLUMN attempt_id uuid REFERENCES processing_attempts (id) ON DELETE SET NULL,
    ADD COLUMN seq bigserial;
CREATE INDEX ix_job_events_job_seq ON job_events (job_id, seq);

-- ---------------------------------------------------------------------------
-- media_assets: provenance
-- ---------------------------------------------------------------------------
ALTER TABLE media_assets
    ADD COLUMN produced_by_attempt_id uuid REFERENCES processing_attempts (id) ON DELETE SET NULL;

-- ---------------------------------------------------------------------------
-- dub_projects: chosen audio stream, archive flag, new milestone status
-- ---------------------------------------------------------------------------
ALTER TABLE dub_projects
    ADD COLUMN source_audio_stream_index integer,
    ADD COLUMN archived_at timestamptz,
    ADD CONSTRAINT ck_dub_projects_audio_stream CHECK (source_audio_stream_index IS NULL OR source_audio_stream_index >= 0),
    DROP CONSTRAINT ck_dub_projects_status,
    ADD CONSTRAINT ck_dub_projects_status CHECK (status IN
        ('CREATED', 'IMPORTED', 'AUDIO_READY', 'TRANSCRIBED', 'TRANSLATED', 'VOICED', 'EXPORTED'));

-- ---------------------------------------------------------------------------
-- processing_profiles: extraction segment length
-- ---------------------------------------------------------------------------
ALTER TABLE processing_profiles
    ADD COLUMN extraction_segment_ms bigint NOT NULL DEFAULT 600000,
    ADD CONSTRAINT ck_processing_profiles_extraction_segment CHECK (extraction_segment_ms BETWEEN 60000 AND 3600000);
